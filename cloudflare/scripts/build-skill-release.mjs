#!/usr/bin/env node
import {
  createHash,
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign,
  verify,
} from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "../..");
const skillRoot = join(repositoryRoot, "integrations/hermes/urgent-caller");
const outputPath = join(repositoryRoot, "cloudflare/src/generated/urgent-caller-release.js");
const defaultKeyPath = join(repositoryRoot, ".secrets/caller-release-ed25519.pem");
const argumentsSet = new Set(process.argv.slice(2));
const checkOnly = argumentsSet.has("--check");
const generateKey = argumentsSet.has("--generate-key");
const keyPath = process.env.CALLER_RELEASE_SIGNING_KEY || defaultKeyPath;

if (checkOnly && !existsSync(keyPath)) {
  await checkGeneratedReleaseWithoutPrivateKey();
  process.exit(0);
}

if (!existsSync(keyPath)) {
  if (!generateKey) {
    throw new Error(
      `Caller release signing key is missing at ${keyPath}. Run with --generate-key once, then back it up securely.`,
    );
  }
  mkdirSync(dirname(keyPath), { recursive: true, mode: 0o700 });
  const { privateKey } = generateKeyPairSync("ed25519");
  writeFileSync(keyPath, privateKey.export({ format: "pem", type: "pkcs8" }), { mode: 0o600 });
  chmodSync(keyPath, 0o600);
}

const privateKey = createPrivateKey(readFileSync(keyPath));
if (privateKey.asymmetricKeyType !== "ed25519") {
  throw new Error("Caller release signing key must be Ed25519");
}
const publicKey = createPublicKey(privateKey);
const publicKeyPEM = publicKey.export({ format: "pem", type: "spki" }).toString();
const publicKeyDER = publicKey.export({ format: "der", type: "spki" });
const publicKeyFingerprint = sha256(publicKeyDER);
const release = JSON.parse(readFileSync(join(skillRoot, "release.json"), "utf8"));
const bootstrap = readFileSync(join(skillRoot, "bootstrap.py"), "utf8");
if (!bootstrap.includes(publicKeyPEM.trimEnd())) {
  throw new Error("bootstrap.py does not pin the public key for the configured release signing key");
}
const sourceFiles = ["SKILL.md", "release.json", "scripts/call.py", "scripts/pair.py", "scripts/update.py"];
const files = {};
const fileEntries = [];

for (const relativePath of sourceFiles) {
  let content = readFileSync(join(skillRoot, relativePath), "utf8");
  if (relativePath === "scripts/update.py" && !content.includes(publicKeyPEM.trimEnd())) {
    throw new Error("scripts/update.py does not pin the public key for the configured release signing key");
  }
  const bytes = Buffer.from(content, "utf8");
  files[relativePath] = content;
  fileEntries.push({ path: relativePath, size: bytes.byteLength, sha256: sha256(bytes) });
}

const manifest = {
  schema_version: release.schema_version,
  skill_name: "urgent-caller",
  skill_version: release.skill_version,
  minimum_supported_version: release.minimum_supported_version,
  released_at: release.released_at,
  change_class: release.change_class,
  requires_user_approval: release.requires_user_approval,
  capabilities: release.capabilities,
  release_notes: release.release_notes,
  signing_key_fingerprint: publicKeyFingerprint,
  files: fileEntries,
};
const canonicalManifest = Buffer.from(canonicalJSON(manifest));
const signature = sign(null, canonicalManifest, privateKey).toString("base64");
const generated = `// Generated by scripts/build-skill-release.mjs. Do not edit by hand.\nexport const URGENT_CALLER_RELEASE = Object.freeze(${JSON.stringify({
  manifest,
  signature,
  files,
  bootstrap,
  bootstrapSha256: sha256(Buffer.from(bootstrap, "utf8")),
}, null, 2)});\n`;

if (checkOnly) {
  if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== generated) {
    throw new Error("Generated urgent-caller release is stale; run npm run build:skill-release");
  }
} else {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
}

console.log(JSON.stringify({
  status: checkOnly ? "current" : "built",
  version: release.skill_version,
  output: outputPath,
  signing_key_fingerprint: publicKeyFingerprint,
}));

function canonicalJSON(value) {
  return JSON.stringify(sortValue(value));
}

function sortValue(value) {
  if (Array.isArray(value)) return value.map(sortValue);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value).sort().map((key) => [key, sortValue(value[key])]),
    );
  }
  return value;
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

async function checkGeneratedReleaseWithoutPrivateKey() {
  if (!existsSync(outputPath)) throw new Error("Generated urgent-caller release is missing");
  const moduleURL = `${pathToFileURL(outputPath).href}?check=${Date.now()}`;
  const { URGENT_CALLER_RELEASE: generatedRelease } = await import(moduleURL);
  const releaseSource = JSON.parse(readFileSync(join(skillRoot, "release.json"), "utf8"));
  const bootstrapSource = readFileSync(join(skillRoot, "bootstrap.py"), "utf8");
  const updaterSource = readFileSync(join(skillRoot, "scripts/update.py"), "utf8");
  const keyMatch = updaterSource.match(
    /TRUSTED_RELEASE_PUBLIC_KEY = """(-----BEGIN PUBLIC KEY-----[\s\S]+?-----END PUBLIC KEY-----)"""/,
  );
  if (!keyMatch) throw new Error("scripts/update.py does not contain a pinned public key");
  if (!bootstrapSource.includes(keyMatch[1])) {
    throw new Error("bootstrap.py and scripts/update.py do not pin the same public key");
  }
  const verificationKey = createPublicKey(keyMatch[1]);
  const fingerprint = sha256(verificationKey.export({ format: "der", type: "spki" }));
  const expectedFiles = {};
  const expectedEntries = [];
  for (const relativePath of ["SKILL.md", "release.json", "scripts/call.py", "scripts/pair.py", "scripts/update.py"]) {
    const content = readFileSync(join(skillRoot, relativePath), "utf8");
    expectedFiles[relativePath] = content;
    expectedEntries.push({
      path: relativePath,
      size: Buffer.byteLength(content),
      sha256: sha256(Buffer.from(content)),
    });
  }
  const expectedManifest = {
    schema_version: releaseSource.schema_version,
    skill_name: "urgent-caller",
    skill_version: releaseSource.skill_version,
    minimum_supported_version: releaseSource.minimum_supported_version,
    released_at: releaseSource.released_at,
    change_class: releaseSource.change_class,
    requires_user_approval: releaseSource.requires_user_approval,
    capabilities: releaseSource.capabilities,
    release_notes: releaseSource.release_notes,
    signing_key_fingerprint: fingerprint,
    files: expectedEntries,
  };
  if (JSON.stringify(generatedRelease.manifest) !== JSON.stringify(expectedManifest)) {
    throw new Error("Generated urgent-caller manifest is stale");
  }
  if (JSON.stringify(generatedRelease.files) !== JSON.stringify(expectedFiles)) {
    throw new Error("Generated urgent-caller files are stale");
  }
  if (
    generatedRelease.bootstrap !== bootstrapSource ||
    generatedRelease.bootstrapSha256 !== sha256(Buffer.from(bootstrapSource))
  ) {
    throw new Error("Generated urgent-caller bootstrap is stale");
  }
  if (!verify(
    null,
    Buffer.from(canonicalJSON(generatedRelease.manifest)),
    verificationKey,
    Buffer.from(generatedRelease.signature, "base64"),
  )) {
    throw new Error("Generated urgent-caller signature is invalid");
  }
  console.log(JSON.stringify({
    status: "current",
    version: releaseSource.skill_version,
    output: outputPath,
    signing_key_fingerprint: fingerprint,
  }));
}
